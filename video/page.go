var universalStatePattern = regexp.MustCompile(`(?is)<script\b[^>]*\bid\s*=\s*["']__UNIVERSAL_DATA_FOR_REHYDRATION__["'][^>]*>(.*?)</script\s*>`)

type pageVideoItem struct {
	ID              string          `json:"id"`
	Description     string          `json:"desc"`
	CreateTime      jsonvalue.Int64 `json:"createTime"`
	LocationCreated string          `json:"locationCreated"`
	Author          struct {
		ID           string `json:"id"`
		SecUID       string `json:"secUid"`
		UniqueID     string `json:"uniqueId"`
		Nickname     string `json:"nickname"`
		Signature    string `json:"signature"`
		Verified     bool   `json:"verified"`
		AvatarLarger string `json:"avatarLarger"`
		AvatarMedium string `json:"avatarMedium"`
		AvatarThumb  string `json:"avatarThumb"`
	} `json:"author"`
	AuthorStats embedAuthorStatistics `json:"authorStats"`
	Stats       struct {
		PlayCount    jsonvalue.Int64 `json:"playCount"`
		DiggCount    jsonvalue.Int64 `json:"diggCount"`
		CommentCount jsonvalue.Int64 `json:"commentCount"`
		ShareCount   jsonvalue.Int64 `json:"shareCount"`
	} `json:"stats"`
	Music struct {
		ID          string `json:"id"`
		Title       string `json:"title"`
		AuthorName  string `json:"authorName"`
		PlayURL     string `json:"playUrl"`
		CoverLarge  string `json:"coverLarge"`
		CoverMedium string `json:"coverMedium"`
		CoverThumb  string `json:"coverThumb"`
	} `json:"music"`
	Challenges []struct {
		ID          string `json:"id"`
		Title       string `json:"title"`
		Description string `json:"desc"`
		IsCommerce  bool   `json:"isCommerce"`
	} `json:"challenges"`
	Video struct {
		ID           string `json:"id"`
		Duration     int    `json:"duration"`
		Width        int    `json:"width"`
		Height       int    `json:"height"`
		Bitrate      int64  `json:"bitrate"`
		Format       string `json:"format"`
		PlayAddr     string `json:"playAddr"`
		Cover        string `json:"cover"`
		OriginCover  string `json:"originCover"`
		DynamicCover string `json:"dynamicCover"`
		BitrateInfo  []struct {
			Bitrate   int64  `json:"Bitrate"`
			CodecType string `json:"CodecType"`
			FPS       int    `json:"BitrateFPS"`
			GearName  string `json:"GearName"`
			PlayAddr  struct {
				DataSize jsonvalue.Int64 `json:"DataSize"`
				Height   int             `json:"Height"`
				Width    int             `json:"Width"`
				URI      string          `json:"Uri"`
				URLList  []string        `json:"UrlList"`
			} `json:"PlayAddr"`
		} `json:"bitrateInfo"`
		CLAInfo struct {
			CaptionInfos []struct {
				Language          string          `json:"lang"`
				CaptionFormat     string          `json:"captionFormat"`
				URL               string          `json:"url"`
				Expire            jsonvalue.Int64 `json:"expire"`
				IsAutoGenerated   bool            `json:"isAutoGenerated"`
				IsOriginalCaption bool            `json:"isOriginalCaption"`
			} `json:"captionInfos"`
		} `json:"claInfo"`
	} `json:"video"`
}

func parsePageVideoItem(body []byte) (*pageVideoItem, error) {
	match := universalStatePattern.FindSubmatch(body)
	if len(match) != 2 {
		return nil, errors.New("video page hydration state was not found")
	}
	var state struct {
		Scope struct {
			VideoDetail struct {
				StatusCode int `json:"statusCode"`
				ItemInfo   struct {
					Item *pageVideoItem `json:"itemStruct"`
				} `json:"itemInfo"`
			} `json:"webapp.video-detail"`
		} `json:"__DEFAULT_SCOPE__"`
	}
	if err := json.Unmarshal(bytes.TrimSpace(match[1]), &state); err != nil {
		return nil, fmt.Errorf("decode video page metadata: %w", err)
	}
	detail := state.Scope.VideoDetail
	if detail.StatusCode != 0 {
		return nil, fmt.Errorf("video page returned status %d", detail.StatusCode)
	}
	if detail.ItemInfo.Item == nil || detail.ItemInfo.Item.ID == "" {
		return nil, errors.New("video page did not contain a video item")
	}
	return detail.ItemInfo.Item, nil
}

func buildPageResult(inputURL, finalURL string, item pageVideoItem) *Result {
	video := item.Video
	info := playerVideoInfo{
		URI:     video.ID,
		URLList: uniqueStrings([]string{video.PlayAddr}),
		Meta:    playerVideoMeta{Duration: video.Duration, Width: video.Width, Height: video.Height, Bitrate: video.Bitrate, Format: video.Format},
	}
	for _, profile := range video.BitrateInfo {
		address := profile.PlayAddr
		info.Profiles = append(info.Profiles, playerProfile{
			Bitrate: profile.Bitrate, CodecType: profile.CodecType, FPS: profile.FPS, GearName: profile.GearName,
			PlayAddr: playerPlayAddress{DataSize: int64(address.DataSize), Height: address.Height, Width: address.Width, URI: address.URI, URLList: uniqueStrings(address.URLList)},
		})
	}
	for _, caption := range video.CLAInfo.CaptionInfos {
		info.CLAInfo.CaptionInfos = append(info.CLAInfo.CaptionInfos, playerCaption{
			Language: caption.Language, CaptionFormat: caption.CaptionFormat, URL: caption.URL, Expire: int64(caption.Expire),
			IsAutoGenerated: caption.IsAutoGenerated, IsOriginalCaption: caption.IsOriginalCaption,
		})
	}
	result := buildPlayerResult(inputURL, finalURL, playerItem{IDStr: item.ID, VideoInfo: info})
	result.Sources = []string{"__UNIVERSAL_DATA_FOR_REHYDRATION__"}
	author, music, stats := item.Author, item.Music, item.Stats
	embed := embedVideoData{
		ItemInfos: embedItem{
			ID: item.ID, Text: item.Description, CreateTime: strconv.FormatInt(int64(item.CreateTime), 10), AuthorID: author.ID,
			LocationCreated: item.LocationCreated, PlayCount: int64(stats.PlayCount), DiggCount: int64(stats.DiggCount), CommentCount: int64(stats.CommentCount), ShareCount: int64(stats.ShareCount),
			Covers: []string{video.Cover}, CoversOrigin: []string{video.OriginCover}, CoversDynamic: []string{video.DynamicCover},
		},
		AuthorInfos: embedAuthor{
			UserID: author.ID, SecUID: author.SecUID, UniqueID: author.UniqueID, Nickname: author.Nickname, Signature: author.Signature, Verified: author.Verified,
			Covers: []string{author.AvatarThumb}, CoversMedium: []string{author.AvatarMedium}, CoversLarger: []string{author.AvatarLarger},
		},
		AuthorStats: item.AuthorStats,
		MusicInfos: embedMusic{
			MusicID: music.ID, MusicName: music.Title, AuthorName: music.AuthorName, PlayURL: []string{music.PlayURL},
			Covers: []string{music.CoverThumb}, CoversMedium: []string{music.CoverMedium}, CoversLarger: []string{music.CoverLarge},
		},
	}
	for _, challenge := range item.Challenges {
		embed.ChallengeInfoList = append(embed.ChallengeInfoList, embedChallenge{ChallengeID: challenge.ID, ChallengeName: challenge.Title, Text: challenge.Description, IsCommerce: challenge.IsCommerce})
	}
	mergeEmbedMetadata(&result.Video, embed)
	if item.CreateTime == 0 {
		result.Video.CreatedAt = nil
	}
	return result
}
