func TestResolveVideoWhenPlayerUnavailable(t *testing.T) {
	t.Parallel()
	for _, test := range []struct {
		name   string
		status int
		body   string
	}{
		{name: "forbidden", status: http.StatusForbidden, body: "denied"},
		{name: "invalid JSON", status: http.StatusOK, body: "<html>challenge</html>"},
		{name: "API error", status: http.StatusOK, body: `{"status_code":10216,"status_msg":"unavailable"}`},
		{name: "empty items", status: http.StatusOK, body: `{"status_code":0,"items":[]}`},
	} {
		t.Run(test.name, func(t *testing.T) {
			client, err := NewClient(ClientOptions{})
			if err != nil {
				t.Fatal(err)
			}
			pageRequests := 0
			client.Session().HTTPClient().Transport = roundTripFunc(func(request *http.Request) (*http.Response, error) {
				status, body := http.StatusOK, desktopVideoPage
				switch request.URL.Path {
				case "/@forever0404_/video/7671176369300327700":
					pageRequests++
					if request.Header.Get("User-Agent") != DefaultUserAgent || strings.Contains(request.Header.Get("User-Agent"), "Mobile") {
						t.Fatalf("expected desktop User-Agent, got %q", request.Header.Get("User-Agent"))
					}
				case "/player/api/v1/items":
					status, body = test.status, test.body
				case "/embed/v2/7671176369300327700":
					status, body = http.StatusForbidden, "denied"
				default:
					t.Fatalf("unexpected request: %s", request.URL.Path)
				}
				return &http.Response{StatusCode: status, Status: http.StatusText(status), Header: make(http.Header), Body: io.NopCloser(strings.NewReader(body)), Request: request}, nil
			})
			inputURL := "https://www.tiktok.com/@forever0404_/video/7671176369300327700"
			result, err := client.Resolve(context.Background(), inputURL)
			if err != nil {
				t.Fatalf("resolve with unavailable player and embed: %v", err)
			}
			if pageRequests != 1 || result.IsStory || result.InputURL != inputURL || result.FinalURL != inputURL {
				t.Fatalf("pageRequests=%d unexpected result: %+v", pageRequests, result)
			}
			video := result.Video
			if video.ID != "7671176369300327700" || video.Description != "Desktop description" || video.Author.UniqueID != "forever0404_" || !video.Author.Verified || video.Author.Statistics.FollowerCount != 100 {
				t.Fatalf("unexpected page metadata: %+v", video)
			}
			if video.CreatedAt == nil || video.CreatedAt.Unix() != 1700000000 || video.Statistics.PlayCount != 500 || video.Music.ID != "music-id" || len(video.Hashtags) != 1 || len(video.Captions) != 1 {
				t.Fatalf("missing page metadata: %+v", video)
			}
			if len(result.Sources) != 2 || result.Sources[0] != "__UNIVERSAL_DATA_FOR_REHYDRATION__" || len(result.Media) != 3 || len(result.Warnings) == 0 {
				t.Fatalf("sources=%v warnings=%v media=%+v", result.Sources, result.Warnings, result.Media)
			}
			best, second, watermarked := result.Media[0], result.Media[1], result.Media[2]
			if best.Height != 1920 || best.Codec != "h265" || best.FPS != 60 || best.Size != 6195244 || best.ExpiresAt == nil || best.Watermarked {
				t.Fatalf("unexpected best profile: %+v", best)
			}
			if len(best.BackupURLs) != 1 || best.BackupURLs[0] != "https://www.tiktok.com/aweme/v1/play/?video_id=1080-uri" || second.Height != 1280 || second.BackupURLs[0] != "https://www.tiktok.com/aweme/v1/play/?video_id=720-uri" || !watermarked.Watermarked {
				t.Fatalf("quality profiles or backups were mixed: %+v", result.Media)
			}
		})
	}
}

func TestResolveVideoPlayerForbiddenUsesEmbedWithoutMarkingStory(t *testing.T) {
	t.Parallel()
	client, err := NewClient(ClientOptions{})
	if err != nil {
		t.Fatal(err)
	}
	client.Session().HTTPClient().Transport = roundTripFunc(func(request *http.Request) (*http.Response, error) {
		status, body := http.StatusOK, "<html>CSR shell</html>"
		switch request.URL.Path {
		case "/player/api/v1/items":
			status, body = http.StatusForbidden, "denied"
		case "/embed/v2/7671176369300327700":
			body = `<script id="__FRONTITY_CONNECT_STATE__">{"source":{"data":{"video":{"code":200,"videoData":{"itemInfos":{"id":"7671176369300327700","video":{"urls":["https://vx-bdp.tiktokv.com/embed.mp4"]}},"authorInfos":{"uniqueId":"forever0404_"}}}}}}</script>`
		}
		return &http.Response{StatusCode: status, Status: http.StatusText(status), Header: make(http.Header), Body: io.NopCloser(strings.NewReader(body)), Request: request}, nil
	})
	result, err := client.Resolve(context.Background(), "https://www.tiktok.com/@forever0404_/video/7671176369300327700")
	if err != nil {
		t.Fatal(err)
	}
	if result.IsStory || len(result.Warnings) != 1 || len(result.Media) != 1 || !result.Media[0].Watermarked {
		t.Fatalf("unexpected embed fallback: %+v", result)
	}
}

func TestResolveVideoRejectsMismatchedPageFallback(t *testing.T) {
	t.Parallel()
	client, err := NewClient(ClientOptions{})
	if err != nil {
		t.Fatal(err)
	}
	client.Session().HTTPClient().Transport = roundTripFunc(func(request *http.Request) (*http.Response, error) {
		status, body := http.StatusForbidden, "denied"
		if strings.Contains(request.URL.Path, "/video/") {
			status, body = http.StatusOK, strings.ReplaceAll(desktopVideoPage, "7671176369300327700", "123456789")
		}
		return &http.Response{StatusCode: status, Status: "403 Forbidden", Header: make(http.Header), Body: io.NopCloser(strings.NewReader(body)), Request: request}, nil
	})
	result, err := client.Resolve(context.Background(), "https://www.tiktok.com/@forever0404_/video/7671176369300327700")
	if result != nil || err == nil || !strings.Contains(err.Error(), "fetch player metadata: HTTP 403 Forbidden") || !strings.Contains(err.Error(), "embed fallback failed") {
		t.Fatalf("result=%+v error=%v", result, err)
	}
}

