func TestResolveVideoCancellationStopsFallback(t *testing.T) {
	t.Parallel()
	client, err := NewClient(ClientOptions{})
	if err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	client.Session().HTTPClient().Transport = roundTripFunc(func(request *http.Request) (*http.Response, error) {
		if request.URL.Path == "/player/api/v1/items" {
			cancel()
			return nil, context.Canceled
		}
		if strings.HasPrefix(request.URL.Path, "/embed/") {
			t.Fatal("embed fallback was requested after cancellation")
		}
		return &http.Response{StatusCode: http.StatusOK, Header: make(http.Header), Body: io.NopCloser(strings.NewReader(desktopVideoPage)), Request: request}, nil
	})
	defer cancel()
	if result, err := client.Resolve(ctx, "https://www.tiktok.com/@forever0404_/video/7671176369300327700"); result != nil || !errors.Is(err, context.Canceled) {
		t.Fatalf("result=%+v error=%v", result, err)
	}
}
